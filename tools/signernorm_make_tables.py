#!/usr/bin/env python
"""GENERATED LaTeX table bodies for P2 \\S A signer-normalized input recipe (tab:signernorm1/2/3).

Every number is computed from result files with the readers of tools/p2_make_tables.py (resolve, r2) and
tools/signernorm_report.py / signernorm_stage2_report.py:
  * accuracies: per-seed Top-1 at 2 dp (r2), 3-seed mean +- population SD, as p2_make_tables;
  * Delta and SMG: differences of the 2-dp DISPLAYED means (as p2_make_tables.smg);
  * 95% CI: hierarchical bootstrap (signernorm_report.hier_ci): per arm the 3 seeds are resampled with
    replacement independently, the 1,365 TEST clips are resampled paired across arms; 10k draws, percentile;
  * LOSO: fold = mean of 3 seeds, SD over the 11 folds (sample), Delta CI = signer-clustered bootstrap (10k);
  * L_norm: probe v2 protocol on each encoder's own feeder input (tools/signernorm_probe.py), class-conditioned.
Fragments are written to docs/signernorm_2026-10/generated/ and to results/tables/generated/ (the published
fragments are in results/tables/reference/). numbers.json holds every value used in the text. Needs the
per-clip TEST score dumps under work_dir/ and data/bdsl_si/test_label.pkl (bootstrap CIs).

  python tools/signernorm_make_tables.py
"""
import csv, json, os, sys
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools")); sys.path.insert(0, ROOT)
os.chdir(ROOT)
import p2_make_tables as T  # noqa: E402
from signernorm_report import summarize, hier_ci, seed_pkls  # noqa: E402
from signernorm_stage2_report import rows_for, mixed_sn, gate, try_resolve, disp  # noqa: E402
from p2_metric_suite import load_labels  # noqa: E402

OUTS = ["docs/signernorm_2026-10/generated", "results/tables/generated"]
HDR = "% GENERATED by tools/signernorm_make_tables.py ({}) -- do not edit by hand; sources: docs/signernorm_2026-10/README.md\n"
S1 = [("base", "Shared feeder (paper)", "bdsl_block_gcn_si_lr01", "bdsl_block_gcn_si_lr01_scratch"),
      ("ctr", "ctr: shoulder-midpoint centring", "bdsl_block_gcn_si_lr01_sn_ctr", None),
      ("a", "+a: + shoulder-width scale", "bdsl_block_gcn_si_lr01_sn_a", None),
      ("ab", "+a+b: + hand-local channels", "bdsl_block_gcn_si_lr01_sn_ab", None),
      ("abc", "+a+b+c: + mirror (\\textbf{adopted})", "bdsl_block_gcn_si_lr01_sn_abc", None),
      ("abcd", "+a+b+c+d: + bone retargeting", "bdsl_block_gcn_si_lr01_sn_abcd", None),
      ("oracle", "+a+b + oracle handedness$^\\dagger$", "bdsl_block_gcn_si_lr01_sn_ab_oraclehand", None)]
CONTRASTS = [("ctr", "base"), ("a", "ctr"), ("ab", "a"), ("abc", "ab"), ("abcd", "abc"), ("abc", "oracle")]
PROBE = "docs/signernorm_2026-10/raw/probe_v2_signernorm.jsonl"
PROBE_KEYS = {"block_gcn": ("bdsl_block_gcn_si_lr01_scratch", "bdsl_block_gcn_si_lr01_sn_abc"),
              "adaptive_gnn": ("bdsl_adaptive_gnn_si_lr0p1", "bdsl_adaptive_gnn_si_lr0p1_sn_abc")}


def pmv(vals):
    v = np.asarray(vals, float)
    return f"{v.mean():.2f}$\\pm${v.std():.2f}"


def ci_cell(lo, hi, dp=1):
    return f"$[{lo:+.{dp}f},{hi:+.{dp}f}]$"


def probe_groups():
    g = {}
    if os.path.isfile(PROBE):
        for l in open(PROBE):
            if l.strip():
                o = json.loads(l)
                g.setdefault(o["tag"].split("@")[0].rsplit("_seed", 1)[0], []).append(o)
    return g


def stage1(lab, nums):
    R = {}
    for key, name, stem, train in S1:
        r = summarize(stem, train or stem, lab, [0, 1, 2])
        if r is None or len(r["seeds"]) < 3:
            raise SystemExit(f"stage1: {stem} incomplete")
        bad = gate([f"{train or stem}_seed{s}" for s in (0, 1, 2)])
        if bad:
            raise SystemExit(f"stage1: incomplete training {bad}")
        R[key] = r
    base_disp = disp(np.mean([T.r2(R["base"]["top1"][s]) for s in (0, 1, 2)]))
    rows, s1 = [], {}
    for key, name, stem, train in S1:
        r = R[key]
        top = [T.r2(r["top1"][s]) for s in (0, 1, 2)]
        per = seed_pkls(stem, [0, 1, 2])
        accL = np.mean([100 * np.mean([np.argmax(d[k]) == lab[k] for k in d if k.endswith("_L.mp4")]) for d in per.values()])
        accR = np.mean([100 * np.mean([np.argmax(d[k]) == lab[k] for k in d if k.endswith("_R.mp4")]) for d in per.values()])
        val = [r["val"][s][0] for s in (0, 1, 2)]
        f1 = float(np.mean(list(r["f1"].values())))
        if key == "base":
            dcell = cicell = "--"; delta = lo = hi = p = None
        else:
            delta = disp(np.mean(top)) - base_disp
            lo, hi, p = hier_ci(r["C"], R["base"]["C"])
            dcell, cicell = f"${delta:+.2f}$", ci_cell(lo, hi)
        rows.append(f"{name} & {pmv(top)} & {dcell} & {cicell} & {f1:.2f} & {pmv(val)} & {accL:.1f} & {accR:.1f} \\\\")
        s1[key] = dict(stem=stem, test=top, test_disp=disp(np.mean(top)), test_sd=float(np.std(top)), f1=f1,
                       val=val, val_disp=disp(np.mean(val)), ens=float(r["ens_top1"]), accL=float(accL),
                       accR=float(accR), delta=delta, ci=[lo, hi], p=p, per_signer_ens=r["per_signer"])
    con = {}
    for a, b in CONTRASTS:
        lo, hi, p = hier_ci(R[a]["C"], R[b]["C"])
        con[f"{a}-{b}"] = dict(delta=s1[a]["test_disp"] - s1[b]["test_disp"], ci=[lo, hi], p=p,
                               ens_delta=float(R[a]["ens_top1"] - R[b]["ens_top1"]))
    nums["stage1"] = s1; nums["stage1_contrasts"] = con
    return rows


def stage2(lab, nums, pg):
    rows = []
    for arch, label, src, st, sdst in rows_for("abc"):
        if arch in ("adaptive_gnn", "gnn") and "lr 0.01" in label:
            continue                                  # paper rows are lr 0.1 (README keeps the lr 0.01 pair)
        name = T.POSE[arch]["names"]["smg8"]
        bt = try_resolve(src["test"]); bm = try_resolve(src["mixed"])
        B = summarize(src["suite"]["stem"], src["suite"]["stem"], lab, [0, 1, 2])
        S = summarize(st, st, lab, [0, 1, 2])
        if bt is None or bm is None or B is None or S is None or len(S["seeds"]) < 3:
            raise SystemExit(f"stage2 {label}: incomplete")
        bad = gate([f"{st}_seed{s}" for s in (0, 1, 2)])
        sm, note = mixed_sn(sdst)
        if bad or note:
            raise SystemExit(f"stage2 {label}: {bad} {note}")
        top = [T.r2(S["top1"][s]) for s in (0, 1, 2)]
        sn = disp(np.mean(top)); p2 = disp(bt.mean)
        delta = sn - p2
        lo, hi, p = hier_ci(S["C"], B["C"])
        f1 = float(np.mean(list(S["f1"].values())))
        smg_b = disp(bm.mean) - p2; smg_s = disp(sm.mean) - sn
        lk = PROBE_KEYS.get(arch)
        if lk and lk[0] in pg and lk[1] in pg:
            lb = float(np.mean([o["cc"] for o in pg[lk[0]]])); ls = float(np.mean([o["cc"] for o in pg[lk[1]]]))
            lcell = f"{lb:.3f}$\\to${ls:.3f}"
        else:
            lb = ls = None; lcell = "--"
        rows.append((sn, f"{name} & {T.pm(bt)} & {pmv(top)} & ${delta:+.2f}$ & {ci_cell(lo, hi, 2)} & {f1:.2f} & "
                         f"{T.pm(sm)} & ${smg_b:+.2f}$ & ${smg_s:+.2f}$ & {lcell} \\\\"))
        nums.setdefault("stage2", {})[arch] = dict(
            p2_test=bt.values, p2_test_disp=p2, sn_test=top, sn_test_disp=sn, delta=delta, ci=[lo, hi], p=p,
            sn_f1=f1, p2_mixed=bm.values, p2_mixed_disp=disp(bm.mean), sn_mixed=sm.values, sn_mixed_disp=disp(sm.mean),
            p2_smg=smg_b, sn_smg=smg_s, lnorm_p2=lb, lnorm_sn=ls, sn_stem=st, p2_suite_stem=src["suite"]["stem"])
    s2 = nums["stage2"]
    nums["stage2_summary"] = dict(
        delta_range=[min(v["delta"] for v in s2.values()), max(v["delta"] for v in s2.values())],
        p2_test_range=[min(v["p2_test_disp"] for v in s2.values()), max(v["p2_test_disp"] for v in s2.values())],
        sn_test_range=[min(v["sn_test_disp"] for v in s2.values()), max(v["sn_test_disp"] for v in s2.values())],
        p2_smg_range=[min(v["p2_smg"] for v in s2.values()), max(v["p2_smg"] for v in s2.values())],
        sn_smg_range=[min(v["sn_smg"] for v in s2.values()), max(v["sn_smg"] for v in s2.values())],
        smg_shrink_range=[min(v["p2_smg"] - v["sn_smg"] for v in s2.values()),
                          max(v["p2_smg"] - v["sn_smg"] for v in s2.values())],
        mixed_change={k: v["sn_mixed_disp"] - v["p2_mixed_disp"] for k, v in s2.items()})
    return [r for _, r in sorted(rows, key=lambda x: -x[0])]


def loso(nums):
    def folds(path):
        per = {}
        for r in csv.DictReader(open(path)):
            per.setdefault(r["heldout_signer"], []).append(float(r["test_acc"]))
        return per
    b = folds("docs/loso_heldout/block_gcn_lr01.csv"); n = folds("docs/loso_heldout/block_gcn_lr01_sn_abc.csv")
    assert set(b) == set(n) and len(n) == 11 and all(len(v) == 3 for v in list(n.values()) + list(b.values()))
    F = sorted(b); B = np.array([np.mean(b[f]) for f in F]); N = np.array([np.mean(n[f]) for f in F]); d = N - B
    rng = np.random.default_rng(1234); idx = rng.integers(0, len(F), size=(10000, len(F)))
    lo, hi = np.percentile(d[idx].mean(1), [2.5, 97.5])
    delta = disp(N.mean()) - disp(B.mean())
    nums["loso"] = dict(p2_mean=disp(B.mean()), p2_sd=float(B.std(ddof=1)), sn_mean=disp(N.mean()),
                        sn_sd=float(N.std(ddof=1)), delta=delta, ci=[float(lo), float(hi)],
                        folds_improved=int((d > 0).sum()), per_fold={f: [float(x), float(y)] for f, x, y in zip(F, B, N)})
    return [f"Shared feeder (paper) & {B.mean():.2f}$\\pm${B.std(ddof=1):.2f} & {B.min():.1f}--{B.max():.1f} & -- & -- \\\\",
            f"+a+b+c & {N.mean():.2f}$\\pm${N.std(ddof=1):.2f} & {N.min():.1f}--{N.max():.1f} & ${delta:+.2f}$ "
            f"$[{lo:+.2f},{hi:+.2f}]$ & {int((d > 0).sum())}/11 \\\\"]


def main():
    lab = load_labels(); nums = {}; pg = probe_groups()
    frags = [("tab_signernorm_s1_rows", stage1(lab, nums)), ("tab_signernorm_s2_rows", stage2(lab, nums, pg)),
             ("tab_signernorm_loso_rows", loso(nums))]
    nums["probe"] = {k: {m: [float(np.mean([o[m] for o in v])), float(np.std([o[m] for o in v])), len(v)]
                         for m in ("cc", "mrg", "wc", "cc_ungrouped")} for k, v in pg.items()}
    for out in OUTS:
        os.makedirs(out, exist_ok=True)
        for name, rows in frags:
            with open(os.path.join(out, name + ".tex"), "w") as f:
                f.write(HDR.format(name) + "\n".join(rows) + "\n")
    json.dump(nums, open(os.path.join(OUTS[0], "numbers.json"), "w"), indent=1, default=float)
    for name, rows in frags:
        print(f"--- {name}\n" + "\n".join(rows))
    print(json.dumps(nums["stage1_contrasts"], indent=1)); print(json.dumps(nums["stage2_summary"], indent=1))


if __name__ == "__main__":
    main()
