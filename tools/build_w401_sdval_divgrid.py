#!/usr/bin/env python
"""BdSLW401 SMG(k) grid on the signer-disjoint-val split (val = S15, test = S04/S08).

Same design as scripts/hpc/slurm_w401_diversity_grid.sbatch / tools/run_diversity_grid.py
(CTR-GCN, 5 random size-k draws per k + the single full-pool draw, seed 0, 20%
class-stratified seen-signer holdout, identical draw/holdout seeding), except:
  * the training-signer pool is the 15 data/bdslw401_si_sdval train signers (S15 removed),
    and each subset's clips come from that bundle's train (= old train+val minus S15);
  * checkpoint selection is on the held-out signer S15 (data/bdslw401_si_sdval/val);
  * the full-pool cell is k=15 (k=16 is infeasible once S15 is excluded).
Unseen TEST = S04/S08 (unchanged); seen TEST = the subset's own holdout.

Writes, per cell, three persistent configs (so tools/run_resumable_seed.py can resume):
  config/w401_sdval_div/bdsl_ctr_gcn_w401_sdval_divk<k>_d<r>.yaml            (train, val=S15)
  config/w401_sdval_div/bdsl_ctr_gcn_w401_sdval_divk<k>_d<r>_unseentest.yaml (test S04/S08)
  config/w401_sdval_div/bdsl_ctr_gcn_w401_sdval_divk<k>_d<r>_seentest.yaml   (seen holdout)
and with --build also materializes data/bdslw401_si_sdval_div/k<k>_d<r>/.

  python tools/build_w401_sdval_divgrid.py --configs            # all 21 cells, configs only
  python tools/build_w401_sdval_divgrid.py --build --cells 2:0 15:0
"""
import argparse, json, os, sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import run_diversity_grid as rdg  # noqa: E402

CANON = ROOT / "data" / "bdslw401_si_sdval"
DIV_ROOT = ROOT / "data" / "bdslw401_si_sdval_div"
POOL = [1, 2, 3, 5, 6, 7, 9, 10, 11, 12, 13, 14, 16, 17, 18]   # 15 train signers (no S15)
BASE = ROOT / "config" / "bdsl_ctr_gcn_w401_sdval.yaml"
CFG_DIR = ROOT / "config" / "w401_sdval_div"
CELLS = [(k, d) for k in (2, 4, 8, 12) for d in range(5)] + [(15, 0)]

rdg.CANON, rdg.DIV_ROOT, rdg.POOL, rdg.REGEX = CANON, DIV_ROOT, POOL, r"S(\d+)"


def rel(p):
    return os.path.relpath(str(p), str(ROOT))


def write_configs(k, d):
    base = yaml.safe_load(open(BASE))
    b = DIV_ROOT / f"k{k}_d{d}"
    stem = f"bdsl_ctr_gcn_w401_sdval_divk{k}_d{d}"
    note = (f"# Auto-generated by tools/build_w401_sdval_divgrid.py: config/bdsl_ctr_gcn_w401_sdval.yaml "
            f"with train = {rel(b)} (signers {rdg.subset_for(k, d)}).\n")
    out = {}
    for tag, (tdata, tlabel) in {
        "": (CANON / "val_data.npy", CANON / "val_label.pkl"),
        "_unseentest": (CANON / "test_data.npy", CANON / "test_label.pkl"),
        "_seentest": (b / "seentest_data.npy", b / "seentest_label.pkl"),
    }.items():
        c = json.loads(json.dumps(base))
        c["Experiment_name"] = stem + tag
        c["train_feeder_args"]["data_path"] = rel(b / "train_data.npy")
        c["train_feeder_args"]["label_path"] = rel(b / "train_label.pkl")
        c["test_feeder_args"]["data_path"] = rel(tdata)
        c["test_feeder_args"]["label_path"] = rel(tlabel)
        p = CFG_DIR / f"{stem}{tag}.yaml"
        with open(p, "w") as f:
            f.write(note)
            yaml.safe_dump(c, f, default_flow_style=False, sort_keys=False)
        out[tag] = p
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cells", nargs="*", help="k:draw list (default all 21)")
    ap.add_argument("--configs", action="store_true")
    ap.add_argument("--build", action="store_true")
    a = ap.parse_args()
    cells = [tuple(int(x) for x in c.split(":")) for c in a.cells] if a.cells else CELLS
    CFG_DIR.mkdir(parents=True, exist_ok=True)
    for k, d in cells:
        if a.configs:
            write_configs(k, d)
        if a.build:
            rdg._ensure_bundle(k, d)
        print(f"k={k} d={d} signers={rdg.subset_for(k, d)}", flush=True)


if __name__ == "__main__":
    main()
