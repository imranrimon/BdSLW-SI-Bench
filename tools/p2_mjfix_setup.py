#!/usr/bin/env python
"""P2 missing-joint fixes (2026-10): write the new configs + packed task lists.

Every config is a COPY of the run the paper reports, with only data paths / eval feeder
(and Experiment_name) changed; existing configs and data are never modified.
  A  masked bone: BlockGCN bone_vec lr 0.01; Adaptive GNN bone at the paper recipe
     (bdsl_adaptive_gnn_bone_clip5 = lr 0.01, grad clip 5.0) and at lr 0.1
  B  masked cues: speednorm_masked, rootcenter_masked (copies of the lr01 cue configs)
  D  Adaptive GNN rand42..46 (lr 0.01), eval feeder = the split's VAL (+ a TEST config)
  E  BlockGCN lr 0.01 paired seenother_{A,B} for U02/U13 (+ frozen-test configs)
  python tools/p2_mjfix_setup.py
"""
import copy
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
CFG = ROOT / "config" / "p2_mjfix"
TASKS = ROOT / "scripts" / "hpc" / "p2_mjfix"
SEEDS = (0, 1, 2)
RS = "python -u tools/run_resumable_seed.py"


def load(p):
    return yaml.safe_load(open(ROOT / p))


def dump(cfg, name):
    p = CFG / name
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "w") as f:
        f.write("# GENERATED by tools/p2_mjfix_setup.py -- P2 missing-joint fixes 2026-10\n")
        yaml.safe_dump(cfg, f, default_flow_style=False, sort_keys=False)
    return str(p.relative_to(ROOT))


def setpaths(cfg, train_dir, eval_dir, eval_split, suffix=""):
    c = copy.deepcopy(cfg)
    c["train_feeder_args"]["data_path"] = f"{train_dir}/train_data{suffix}.npy"
    c["train_feeder_args"]["label_path"] = f"{train_dir}/train_label.pkl"
    c["test_feeder_args"]["data_path"] = f"{eval_dir}/{eval_split}_data{suffix}.npy"
    c["test_feeder_args"]["label_path"] = f"{eval_dir}/{eval_split}_label.pkl"
    return c


def pair(cfg, name, train_dir, suffix=""):
    """train config (eval on val) + test config (eval on test) of one condition."""
    tr = setpaths(cfg, train_dir, train_dir, "val", suffix); tr["Experiment_name"] = name
    te = setpaths(cfg, train_dir, train_dir, "test", suffix); te["Experiment_name"] = name + "_test"
    return tr, te


def main():
    tasks = {k: [] for k in ("bone_blockgcn", "bone_adaptive", "cue", "rand", "pair")}

    # ---------------- A: masked bone ----------------
    BM = "data/bdsl_si_bonemask"
    src = load("config/lr01_switch/bdsl_block_gcn_si_bone_vec_lr01.yaml")
    tr, te = pair(src, "bdsl_block_gcn_si_bonemask_vec_lr01", BM, "_bone")
    a, b = dump(tr, "bdsl_block_gcn_si_bonemask_vec_lr01.yaml"), dump(te, "bdsl_block_gcn_si_bonemask_vec_lr01_test.yaml")
    for s in SEEDS:
        tasks["bone_blockgcn"].append(f"{RS} --config {a} --seed {s} --exp bdsl_block_gcn_si_bonemask_vec_lr01_seed{s} "
                                      f"--test-config {b} --test-exp bdsl_block_gcn_si_bonemask_vec_lr01_test_seed{s}")
    # Adaptive bone, paper recipe = work_dir/bdsl_adaptive_gnn_bone_clip5_seed*/config.yaml
    # (config/bdsl_adaptive_gnn_bone.yaml + grad_clip_norm 5.0, save_interval 2, eval_interval 5)
    src = load("config/bdsl_adaptive_gnn_bone.yaml"); src["grad_clip_norm"] = 5.0
    tr, te = pair(src, "bdsl_adaptive_gnn_bonemask_clip5", "./" + BM, "_bone")
    a, b = dump(tr, "bdsl_adaptive_gnn_bonemask_clip5.yaml"), dump(te, "bdsl_adaptive_gnn_bonemask_clip5_test.yaml")
    for s in SEEDS:
        tasks["bone_adaptive"].append(f"{RS} --config {a} --seed {s} --exp bdsl_adaptive_gnn_bonemask_clip5_seed{s} "
                                      f"--test-config {b} --test-exp bdsl_adaptive_gnn_bonemask_clip5_test_seed{s}")
    src = load("config/lr0p1_switch/bdsl_adaptive_gnn_bone_lr0p1.yaml")
    tr, te = pair(src, "bdsl_adaptive_gnn_bonemask_lr0p1", "./" + BM, "_bone")
    a, b = dump(tr, "bdsl_adaptive_gnn_bonemask_lr0p1.yaml"), dump(te, "bdsl_adaptive_gnn_bonemask_lr0p1_test.yaml")
    for s in SEEDS:
        tasks["bone_adaptive"].append(f"{RS} --config {a} --seed {s} --exp bdsl_adaptive_gnn_bonemask_lr0p1_seed{s} "
                                      f"--test-config {b} --test-exp bdsl_adaptive_gnn_bonemask_lr0p1_test_seed{s}")

    # ---------------- B: masked cues (final-epoch TEST estimator, as the paper) ----------------
    for cue, old in (("speednorm_masked", "speednorm"), ("rootcenter_masked", "rootcenter")):
        src = load(f"config/lr01_switch/bdsl_cue_{old}_lr01.yaml")
        c = setpaths(src, f"data/bdsl_cue_{cue}", f"data/bdsl_cue_{cue}", "test")
        c["Experiment_name"] = f"bdsl_cue_{cue}_lr01"
        p = dump(c, f"bdsl_cue_{cue}_lr01.yaml")
        for s in SEEDS:
            tasks["cue"].append(f"{RS} --config {p} --seed {s} --exp bdsl_cue_{cue}_lr01_seed{s}")

    # ---------------- D: val-selected matched random splits (Adaptive GNN, lr 0.01, seed 0) ----------------
    for r in range(42, 47):
        src = load(f"config/bdsl_adaptive_gnn_rand{r}.yaml")
        tr, te = pair(src, f"bdsl_adaptive_gnn_rand{r}_valsel", f"./data/bdsl_rand{r}")
        a, b = dump(tr, f"bdsl_adaptive_gnn_rand{r}_valsel.yaml"), dump(te, f"bdsl_adaptive_gnn_rand{r}_valsel_test.yaml")
        tasks["rand"].append(f"{RS} --config {a} --seed 0 --exp bdsl_adaptive_gnn_rand{r}_valsel_seed0 "
                             f"--test-config {b} --test-exp bdsl_adaptive_gnn_rand{r}_valsel_test_seed0")

    # ---------------- E: paired, focus signer seen only through other classes ----------------
    src = load("config/bdsl_block_gcn_si_lr01.yaml")
    for f in (2, 13):
        for h in ("A", "B"):
            cond = f"U{f:02d}_seenother_{h}"
            stem = f"bdsl_block_gcn_si_lr01_pairsmg_{cond}"
            tr, te = pair(src, stem, f"data/bdsl_si_pairsmg_seenother/{cond}")
            a, b = dump(tr, f"pairsmg/{stem}.yaml"), dump(te, f"pairsmg/{stem}_test.yaml")
            for s in SEEDS:
                tasks["pair"].append(f"{RS} --config {a} --seed {s} --exp {stem}_seed{s} "
                                     f"--test-config {b} --test-exp {stem}_seed{s}_test")

    TASKS.mkdir(parents=True, exist_ok=True)
    for k, v in tasks.items():
        (TASKS / f"tasks_{k}.txt").write_text("\n".join(v) + "\n")
        print(f"{k}: {len(v)} tasks -> scripts/hpc/p2_mjfix/tasks_{k}.txt")


if __name__ == "__main__":
    main()
