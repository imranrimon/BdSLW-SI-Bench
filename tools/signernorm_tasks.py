#!/usr/bin/env python
"""Configs + packed task lists for the signer-normalized pose recipe (docs/signernorm_2026-10/).

Stage 1: BlockGCN lr 0.01 additive ablation (a, ab, abc, abcd) x 3 seeds, Protocol A
(select on val U15, TEST-eval the best checkpoint with the *_test config).
Configs are copies of the canonical Track-A configs with only the feeder (+ args) changed
(+ model in_channels 5 when hand_local adds two channels).

  python tools/signernorm_tasks.py stage1
"""
import argparse, glob, os
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CFG = os.path.join(ROOT, "config", "signernorm")
TASKS = os.path.join(ROOT, "scripts", "hpc", "signernorm")
FEEDER = "feeders_signernorm.SignerNormFeeder"  # top-level shim (see feeders_signernorm.py)

# recipe components (train-side, test-side)
COMP = {
    "a": (dict(body_frame=True, normalization=False), dict(body_frame=True, normalization=False)),
    "b": (dict(hand_local=True), dict(hand_local=True)),
    "c": (dict(random_mirror=True, random_mirror_p=0.5), {}),
    "d": (dict(bone_aug="signer", bone_aug_p=0.5), {}),
    # centring-only control: shoulder-midpoint centring, no scaling, padding/missing kept at 0
    "0": (dict(body_frame=True, body_scale="none", normalization=False),
          dict(body_frame=True, body_scale="none", normalization=False)),
    # ORACLE handedness canonicalization (filename _L/_R metadata; upper bound, not deployable)
    "o": (dict(oracle_hand_canon=True), dict(oracle_hand_canon=True)),
}


def make(base_cfg, base_test_cfg, tag, comps, out_stem, test_data=None, subdir=""):
    """Write config/signernorm/<subdir>/<out_stem>.yaml and _test.yaml; return (cfg_path, test_path).

    base_test_cfg None -> the test config is base_cfg with test_feeder_args data swapped to test_data
    (a (data.npy, label.pkl) pair)."""
    cfg = yaml.safe_load(open(os.path.join(ROOT, base_cfg)))
    tcfg = yaml.safe_load(open(os.path.join(ROOT, base_test_cfg or base_cfg)))
    if test_data:
        tcfg["test_feeder_args"]["data_path"], tcfg["test_feeder_args"]["label_path"] = test_data
    for c in (cfg, tcfg):
        c["feeder"] = FEEDER
        c["Experiment_name"] = out_stem
        for k in (["0"] if comps == "ctr" else comps):
            tr, te = COMP[k]
            c["train_feeder_args"].update(tr)
            c["test_feeder_args"].update(te)
        if "b" in comps:
            c["model_args"]["in_channels"] = c["model_args"].get("in_channels", 3) + 2
    hdr = (f"# signer-normalized recipe '{tag}' (docs/signernorm_2026-10/). Generated by tools/signernorm_tasks.py\n"
           f"# from {{src}}: only the feeder + its args changed (and in_channels +2 for hand-local channels).\n")
    paths = []
    os.makedirs(os.path.join(CFG, subdir), exist_ok=True)
    for c, src, suf in ((cfg, base_cfg, ""), (tcfg, base_test_cfg or f"{base_cfg} (test data swapped)", "_test")):
        p = os.path.join(CFG, subdir, f"{out_stem}{suf}.yaml")
        with open(p, "w") as f:
            f.write(hdr.format(src=src))
            yaml.safe_dump(c, f, sort_keys=False)
        paths.append(os.path.relpath(p, ROOT))
    return paths


def cmd(cfg, tcfg, stem, seed):
    return (f"python -u tools/run_resumable_seed.py --config {cfg} --seed {seed} --exp {stem}_seed{seed} "
            f"--test-config {tcfg} --test-exp {stem}_seed{seed}_test")


def stage1_ctl():
    """Centring-only control (fixes Feeder's padding-inclusive centring, no signer scaling)."""
    stem = "bdsl_block_gcn_si_lr01_sn_ctr"
    cfg, tcfg = make("config/bdsl_block_gcn_si_lr01.yaml", "config/bdsl_block_gcn_si_lr01_test.yaml",
                     "ctr (centring only)", "ctr", stem)
    lines = [cmd(cfg, tcfg, stem, s) for s in (0, 1, 2)]
    with open(os.path.join(TASKS, "tasks_S1_ctl.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


def stage1():
    os.makedirs(CFG, exist_ok=True); os.makedirs(TASKS, exist_ok=True)
    lines = []
    for tag in ("a", "ab", "abc", "abcd"):
        stem = f"bdsl_block_gcn_si_lr01_sn_{tag}"
        cfg, tcfg = make("config/bdsl_block_gcn_si_lr01.yaml", "config/bdsl_block_gcn_si_lr01_test.yaml",
                         tag, tag, stem)
        lines += [cmd(cfg, tcfg, stem, s) for s in (0, 1, 2)]
    # two 2-GPU jobs, 6 runs each (3 per GPU); interleave so each job mixes conditions
    for j in range(2):
        with open(os.path.join(TASKS, f"tasks_S1_{j}.txt"), "w") as f:
            f.write("\n".join(lines[j::2]) + "\n")
    print("\n".join(lines))


ARCHS = ["adaptive_gnn", "st_gcn_vanilla", "slgtformer", "gnn", "gnn_lstm", "gnn_transformer", "pose_lstm"]
SD_TEST = ("data/bdsl_sd/test_data.npy", "data/bdsl_sd/test_label.pkl")


def _write(name, lines):
    with open(os.path.join(TASKS, f"tasks_{name}.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")


def stage2(recipe="abc"):
    """Best Stage-1 recipe on the 7 other pose archs (Protocol A), all 8 archs on symmetric Mixed (bdsl_sd),
    BlockGCN held-out LOSO (11 folds), and the oracle-handedness BlockGCN variant. One task list per job:
    SLGTFormer = 1 run per 1-GPU job (12.6 GB); others = 3 runs (one arch's 3 seeds) per 1-GPU job."""
    jobs = {}
    for arch in ARCHS:                                   # Protocol A (BlockGCN abc = Stage 1)
        base = "config/bdsl_gnn_transformer_si_clip5.yaml" if arch == "gnn_transformer" else f"config/bdsl_{arch}_si.yaml"
        stem = f"bdsl_{arch}_si_sn_{recipe}"
        cfg, tcfg = make(base, f"config/bdsl_{arch}_si_test.yaml", recipe, recipe, stem, subdir="stage2")
        L = [cmd(cfg, tcfg, stem, s) for s in (0, 1, 2)]
        if arch == "slgtformer":
            for s in range(3): jobs[f"S2si_slgt_s{s}"] = [L[s]]
        else:
            jobs[f"S2si_{arch}"] = L
    for arch in ["block_gcn"] + ARCHS:                   # symmetric Mixed (SMG = Mixed - TEST)
        if arch == "block_gcn":
            base, tbase = "config/lr01_switch/bdsl_block_gcn_sd_lr01.yaml", None
        elif arch == "gnn_transformer":
            base, tbase = "config/bdsl_gnn_transformer_sd_clip5.yaml", None
        else:
            base, tbase = f"config/bdsl_{arch}_sd_noclip.yaml", f"config/bdsl_{arch}_sd_noclip_test.yaml"
        stem = f"bdsl_{arch}_sd_sn_{recipe}"
        cfg, tcfg = make(base, tbase, recipe, recipe, stem, test_data=SD_TEST if tbase is None else None,
                         subdir="stage2")
        L = [cmd(cfg, tcfg, stem, s) for s in (0, 1, 2)]
        if arch == "slgtformer":
            for s in range(3): jobs[f"S2sd_slgt_s{s}"] = [L[s]]
        else:
            jobs[f"S2sd_{arch}"] = L
    for fold in sorted(glob.glob(os.path.join(ROOT, "data/bdsl_si_loso/test_U*_val_U*"))):   # held-out LOSO
        fd = os.path.basename(fold); nn = fd.split("_")[1][1:]
        base = f"config/lr01_switch/loso/bdsl_block_gcn_si_lr01_loso_test{nn}.yaml"
        stem = f"bdsl_block_gcn_si_lr01_sn_{recipe}_loso_test{nn}"
        cfg, tcfg = make(base, None, recipe, recipe, stem, subdir="loso",
                         test_data=(f"data/bdsl_si_loso/{fd}/test_data.npy", f"data/bdsl_si_loso/{fd}/test_label.pkl"))
        jobs[f"S2loso_{nn}"] = [cmd(cfg, tcfg, stem, s) for s in (0, 1, 2)]
    stem = "bdsl_block_gcn_si_lr01_sn_ab_oraclehand"     # oracle handedness (metadata upper bound)
    cfg, tcfg = make("config/bdsl_block_gcn_si_lr01.yaml", "config/bdsl_block_gcn_si_lr01_test.yaml",
                     "ab + ORACLE handedness canonicalization", "abo", stem)
    jobs["S2oracle"] = [cmd(cfg, tcfg, stem, s) for s in (0, 1, 2)]
    for k, v in jobs.items(): _write(k, v)
    with open(os.path.join(TASKS, "stage2_jobs.txt"), "w") as f:
        f.write("\n".join(jobs) + "\n")
    print(len(jobs), "jobs,", sum(map(len, jobs.values())), "runs")


def stage2_lr0p1(recipe="abc"):
    """Adaptive GNN + Attention GNN at the paper's switched base LR 0.1 (docs/adaptive_attn_lr0p1_switch/),
    so the SN rows are recipe-matched to the current P2 rows (Stage 2 ran them at the earlier lr 0.01)."""
    jobs = {}
    for arch in ("adaptive_gnn", "gnn"):
        stem = f"bdsl_{arch}_si_lr0p1_sn_{recipe}"
        cfg, tcfg = make(f"config/lrsweep/bdsl_{arch}_si_lr0p1.yaml", f"config/bdsl_{arch}_si_test.yaml",
                         recipe, recipe, stem, subdir="stage2")
        jobs[f"S2si_{arch}_lr0p1"] = [cmd(cfg, tcfg, stem, s) for s in (0, 1, 2)]
        stem = f"bdsl_{arch}_sd_lr0p1_sn_{recipe}"
        cfg, tcfg = make(f"config/lr0p1_switch/bdsl_{arch}_sd_noclip_lr0p1.yaml",
                         f"config/lr0p1_switch/bdsl_{arch}_sd_noclip_lr0p1_test.yaml", recipe, recipe, stem,
                         subdir="stage2")
        jobs[f"S2sd_{arch}_lr0p1"] = [cmd(cfg, tcfg, stem, s) for s in (0, 1, 2)]
    for k, v in jobs.items(): _write(k, v)
    print(" ".join(jobs))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("stage", choices=["stage1", "stage1_ctl", "stage2", "stage2_lr0p1"])
    a = ap.parse_args()
    globals()[a.stage]()
